import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context = vm.createContext({ window: {} });
for (const name of ['text-model', 'remote-text-document']) vm.runInContext(fs.readFileSync(new URL(`../web/${name}.js`, import.meta.url), 'utf8'), context);
context.DengTextModel = context.window.DengTextModel;
const Document = context.window.DengRemoteTextDocument;
const reads = [], writes = [];
const transport = {
  api: url => new Promise((resolve, reject) => reads.push({ url, resolve, reject })),
  post: (url, body) => new Promise((resolve, reject) => writes.push({ url, body, resolve, reject })),
};
const file = (text, sha256 = text, encoding = 'utf-8') => ({ path: '/same.conf', text, sha256, encoding });
const a = new Document({ id: 'server-a' }, '/same.conf', () => {}, transport);
const b = new Document({ id: 'server-b' }, '/same.conf', () => {}, transport);
const early = a.load('gbk'), later = a.load(), other = b.load();
assert.equal(a.loading, true);
reads[1].resolve(file('A\r\n')); await later;
a.model.edit('unsaved A\n'); const model = a.model;
reads[2].resolve(file('B\n')); await other;
reads[0].resolve(file('stale', 'old', 'gbk')); await early;
assert.equal(a.model, model); assert.equal(a.model.raw, 'unsaved A\r\n');
assert.equal(a.baseline.encoding, 'utf-8'); assert.equal(b.model.raw, 'B\n');
const fail = a.load('gbk');
assert.equal(await a.save(), false); assert.equal(writes.length, 0);
reads[3].reject(new Error('decode failed')); await assert.rejects(fail, /decode failed/);
assert.equal(a.model, model); assert.equal(a.loading, false); assert.equal(a.dirty, true);
const staleFail = a.load(), winning = a.load();
reads[5].resolve(file('latest')); await winning; a.model.edit('edited latest');
reads[4].reject(new Error('stale failure')); await staleFail;
assert.equal(a.model.raw, 'edited latest'); assert.equal(a.error, '');
b.model.edit('edited B\n');
const saveA = a.save(), saveB = b.save();
assert.equal(writes[0].url, '/api/sessions/server-a/file-content');
assert.equal(writes[1].url, '/api/sessions/server-b/file-content');
assert.equal(writes[0].body.sha256, 'latest'); assert.equal(writes[1].body.sha256, 'B\n');
a.model.edit('new edit during save');
writes[1].resolve(file('edited B\n', 'B-v2')); await saveB;
writes[0].resolve(file('edited latest', 'A-v2')); await saveA;
assert.equal(a.model.raw, 'new edit during save'); assert.equal(a.dirty, true);
assert.equal(b.dirty, false); assert.equal(b.baseline.sha256, 'B-v2');
a.model.undo(); assert.equal(a.model.raw, 'edited latest'); assert.equal(a.dirty, false);
a.model.redo();
const conflict = a.save(); assert.equal(writes[2].body.sha256, 'A-v2');
writes[2].reject(new Error('remote file changed')); await assert.rejects(conflict, /remote file changed/);
assert.equal(a.dirty, true); assert.equal(a.saving, false); assert.equal(a.model.raw, 'new edit during save');
const closed = a.load(); a.close(); reads[6].resolve(file('response after close')); await closed;
assert.equal(a.model.raw, 'new edit during save');
console.log('PASS: cross-server isolation; stale/failed reads; load/save guards; in-flight edits/undo; save target/hash; conflicts and close races.');
