import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const ctx=vm.createContext({window:{}});
for(const file of ['web/text-model.js','web/text-search.js'])vm.runInContext(fs.readFileSync(file,'utf8'),ctx);
const {DengTextModel:Model,DengTextSearch:s}=ctx.window;
const plain=o=>JSON.parse(JSON.stringify(o));
assert.deepEqual(plain(s.scan('foo FOO foo','foo',false,0,3)),{count:3,current:1,next:[4,7],previous:[8,11]});
assert.equal(s.scan('foo FOO foo','foo',true).count,2);
assert.equal(s.scan('a.b a+b [x] $&','a.b',false).count,1);
assert.equal(s.scan('😀 K K k','k',false).count,3);
assert.equal(s.scan('abc','',false).count,0);
assert.equal(s.scan('abc','xyz',false).next,null);
assert.equal(s.scan('a'.repeat(2_000_000),'a',false).count,2_000_000);
assert.deepEqual(plain(s.lineRange('一\n\n😀\n',3)),[3,5]);
assert.deepEqual(plain(s.lineRange('一\n\n😀\n',4)),[6,6]);
for(const n of [0,-1,1.5,5,NaN,Infinity])assert.equal(s.lineRange('一\n\n😀\n',n),null);
assert.deepEqual(plain(s.lineRange('',1)),[0,0]);
const a=new Model('foo\r\nFOO\rfoo\n末尾'),b=new Model(a.raw);
const replacement=s.replaceAll(a.raw,'foo','$&',false);
assert.equal(replacement.count,3);assert.equal(replacement.raw,'$&\r\n$&\r$&\n末尾');
a.checkpoint();a.raw=replacement.raw;a.undo();assert.equal(a.raw,b.raw);a.redo();assert.equal(a.raw,replacement.raw);
assert.equal(s.replaceAll('a\r\nb\ra\nb','a\nb','x',true).raw,'x\rx');
assert.equal(s.replaceAll('aaaa','aa','aa',true).count,2);
assert.equal(s.replaceAll('aaa','a','',true).raw,'');
console.log('PASS literal/Unicode/case/wrap search; bounded match memory; line validation; original CRLF/CR/LF; literal replacement; undo/redo isolation');
